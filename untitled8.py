import pandas as pd


def validate_and_clean(df: pd.DataFrame):
    """Validate and clean student service request data."""

    if not isinstance(df, pd.DataFrame):
        raise TypeError("Input must be a pandas DataFrame.")

    if df.empty:
        raise ValueError("The uploaded CSV contains no records.")

    cleaned = df.copy()

    # Clean column names
    cleaned.columns = [str(col).strip() for col in cleaned.columns]

    # Remove empty rows and columns
    cleaned.dropna(how="all", inplace=True)
    cleaned.dropna(axis=1, how="all", inplace=True)

    if cleaned.empty:
        raise ValueError("No valid records found after cleaning.")

    # Convert blank strings to missing values
    for col in cleaned.select_dtypes(include=["object", "string"]).columns:
        cleaned[col] = cleaned[col].replace(
            r"^\s*$", pd.NA, regex=True
        )

    # Remove duplicate request IDs
    id_candidates = [
        "Request_ID",
        "Request ID",
        "request_id",
        "RequestID",
        "Ticket_ID",
        "Ticket ID"
    ]

    id_col = next(
        (col for col in id_candidates if col in cleaned.columns),
        None
    )

    duplicate_ids = 0

    if id_col is not None:
        duplicate_mask = (
            cleaned[id_col].notna()
            & cleaned[id_col].duplicated(keep="first")
        )

        duplicate_ids = int(duplicate_mask.sum())
        cleaned = cleaned.loc[~duplicate_mask].copy()

    # Validate date columns
    invalid_dates = 0

    for col in cleaned.columns:
        if any(word in col.lower() for word in ["date", "time", "timestamp"]):
            original = cleaned[col]
            converted = pd.to_datetime(original, errors="coerce")

            invalid_dates += int(
                (original.notna() & converted.isna()).sum()
            )

            cleaned[col] = converted

    # Validate numeric columns
    negative_values = 0

    for col in cleaned.columns:
        if pd.api.types.is_datetime64_any_dtype(cleaned[col]):
            continue

        if any(word in col.lower() for word in ["id", "phone", "contact"]):
            continue

        if pd.api.types.is_numeric_dtype(cleaned[col]):
            numeric = pd.to_numeric(cleaned[col], errors="coerce")

            negative_mask = numeric < 0
            negative_values += int(negative_mask.sum())

            cleaned[col] = numeric.mask(negative_mask)

    # Validate satisfaction scores (1 to 5)
    invalid_satisfaction = 0

    sat_col = next(
        (
            col for col in cleaned.columns
            if col.lower().replace(" ", "_") in [
                "satisfaction_score",
                "satisfaction",
                "satisfaction_rating"
            ]
        ),
        None
    )

    if sat_col is not None:
        scores = pd.to_numeric(
            cleaned[sat_col], errors="coerce"
        )

        invalid_mask = (
            scores.notna() & ~scores.between(1, 5)
        )

        invalid_satisfaction = int(invalid_mask.sum())

        cleaned[sat_col] = scores.mask(invalid_mask)

    report = {
        "duplicate_ids": duplicate_ids,
        "invalid_dates": invalid_dates,
        "negative_values": negative_values,
        "invalid_satisfaction": invalid_satisfaction
    }

    return cleaned.reset_index(drop=True), report